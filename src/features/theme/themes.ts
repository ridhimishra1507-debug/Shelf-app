export const defaultThemeId: ThemeId = 'old-library';

export function isThemeId(value: string | null | undefined): value is ThemeId {
  return typeof value === 'string' && (themeIds as readonly string[]).includes(value);
}

export function getTheme(themeId: ThemeId | null | undefined): ShelfTheme {
  const resolvedThemeId = isThemeId(themeId) ? themeId : defaultThemeId;

  return themes.find((theme) => theme.id === resolvedThemeId) ?? themes[0];
}

